#!/usr/bin/env node
/*
 * CXWorks site build — zero dependencies (Node 14+).
 *
 *   node build.js           build index.html once
 *   node build.js --watch   rebuild whenever src/ or js/data/ changes
 *
 * What it does:
 *   1. Reads src/index.template.html
 *   2. Replaces every  <!-- @include path.html -->  with the file from src/templates/
 *      (includes can nest).
 *   3. Replaces  <!-- @data-scripts -->  with a <script> tag for every file in js/data/
 *      (sorted by name) and every insight in js/data/blog/ (placed after 07-blog-init.js).
 *   4. Writes index.html.
 *
 * CSS, js/app.js and the data files are linked, not inlined, so editing those needs
 * NO rebuild — just refresh. Rebuild only after editing src/ templates or adding /
 * removing / renaming a data or blog file.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const TPL_DIR = path.join(ROOT, 'src', 'templates');
const DATA_DIR = path.join(ROOT, 'js', 'data');
const BLOG_DIR = path.join(DATA_DIR, 'blog');

function include(text, stack) {
  return text.replace(/<!-- @include (\S+) -->/g, (_, rel) => {
    const file = path.join(TPL_DIR, rel);
    if (stack.includes(file)) throw new Error('Circular include: ' + [...stack, file].join(' -> '));
    if (!fs.existsSync(file)) throw new Error('Missing partial: src/templates/' + rel);
    return include(fs.readFileSync(file, 'utf8').replace(/\n$/, ''), [...stack, file]);
  });
}

function dataScripts() {
  const js = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
  const tags = [];
  for (const f of js(DATA_DIR)) {
    tags.push(`<script src="js/data/${f}"></script>`);
    if (f === '07-blog-init.js' && fs.existsSync(BLOG_DIR)) {
      for (const b of js(BLOG_DIR)) tags.push(`<script src="js/data/blog/${b}"></script>`);
    }
  }
  return tags.join('\n');
}

function build() {
  const t0 = Date.now();
  let html = fs.readFileSync(path.join(ROOT, 'src', 'index.template.html'), 'utf8');
  html = html.replace('<!-- @generated-notice -->',
    '<!-- GENERATED by build.js from src/ — do not edit this file directly; edit src/ and run: node build.js -->');
  html = html.replace('<!-- @data-scripts -->', dataScripts());
  html = include(html, []);
  const left = html.match(/<!-- @include \S+ -->/);
  if (left) throw new Error('Unresolved include: ' + left[0]);
  fs.writeFileSync(path.join(ROOT, 'index.html'), html);
  console.log(`[build] index.html written (${(html.length / 1024).toFixed(0)} KB) in ${Date.now() - t0} ms`);
}

try { build(); } catch (e) { console.error('[build] ' + e.message); process.exitCode = 1; }

if (process.argv.includes('--watch')) {
  let timer = null;
  const again = () => { clearTimeout(timer); timer = setTimeout(() => { try { build(); } catch (e) { console.error('[build] ' + e.message); } }, 120); };
  for (const dir of [path.join(ROOT, 'src'), TPL_DIR, ...fs.readdirSync(TPL_DIR).map((d) => path.join(TPL_DIR, d)), DATA_DIR, BLOG_DIR]) {
    if (fs.existsSync(dir) && fs.statSync(dir).isDirectory()) fs.watch(dir, again);
  }
  console.log('[build] watching src/ and js/data/ ...');
}
